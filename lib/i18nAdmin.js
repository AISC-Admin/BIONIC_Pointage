// Mois (le code affiche les mois en francais, avec ou sans accents).
const MOIS_FR = ['janvier', 'fevrier', 'mars', 'avril', 'mai', 'juin', 'juillet', 'aout', 'septembre', 'octobre', 'novembre', 'decembre'];
const MOIS = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  es: ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre']
};
const RE_MOIS = /\b(janvier|f[ée]vrier|mars|avril|mai|juin|juillet|ao[uû]t|septembre|octobre|novembre|d[ée]cembre)\b/gi;

function sansAccent(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '');
}

function traduireMois(texte, lang) {
  return texte.replace(RE_MOIS, (m) => {
    const i = MOIS_FR.indexOf(sansAccent(m).toLowerCase());
    if (i < 0) return m;
    const t = MOIS[lang][i];
    // Majuscule conservee (« Octobre 2026 » -> « October 2026 » / « Octubre 2026 »).
    return m[0] === m[0].toUpperCase() ? t.charAt(0).toUpperCase() + t.slice(1) : t;
  });
}

