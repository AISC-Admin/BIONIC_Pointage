// Traduit un texte francais (si connu) dans la langue demandee.
export function traduireAdmin(texte, lang) {
  if (!texte || lang === 'fr' || !(lang in IDX)) return texte;
  const m = texte.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const debut = m[1];
  const coeur = m[2];
  const fin = m[3];
  if (!coeur) return texte;
  const exact = DICT[coeur];
  if (exact) return debut + exact[IDX[lang]] + fin;
  for (const [re, en, es] of MOTIFS) {
    if (re.test(coeur)) {
      const remplace = coeur.replace(re, lang === 'en' ? en : es);
      return debut + traduireMois(remplace, lang) + fin;
    }
  }
  if (RE_MOIS.test(coeur)) {
    RE_MOIS.lastIndex = 0;
    return debut + traduireMois(coeur, lang) + fin;
  }
  return texte;
}
